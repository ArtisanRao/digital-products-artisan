// scripts/generate-image-manifest.mjs
import fs from "fs"
import path from "path"

const ROOT = process.cwd()
const BASE_DIR = path.join(ROOT, "public", "images", "products")
const OUT_TS = path.join(ROOT, "data", "image-manifest.ts")

// natural sort so "...-10.jpg" comes after "...-9.jpg"
const naturalCompare = (a, b) => {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" })
}

const exts = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif"])

const exists = fs.existsSync(BASE_DIR)
if (!exists) {
  console.error(`Directory not found: ${BASE_DIR}`)
  process.exit(1)
}

const slugs = fs
  .readdirSync(BASE_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)

const manifest = {}

for (const slug of slugs) {
  const dir = path.join(BASE_DIR, slug)
  const files = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((f) => f.isFile())
    .map((f) => f.name)
    .filter((name) => exts.has(path.extname(name).toLowerCase()))

  // put cover first if present, then the rest in natural order
  const cover = files.find((f) => f.toLowerCase().includes("cover"))
  const rest = files
    .filter((f) => f !== cover)
    .sort(naturalCompare)

  const ordered = (cover ? [cover] : []).concat(rest)

  manifest[slug] = ordered.map((fname) => `/images/products/${slug}/${fname}`)
}

const file = `// AUTO-GENERATED by scripts/generate-image-manifest.mjs
export const imageManifest: Record<string, string[]> = ${JSON.stringify(
  manifest,
  null,
  2
)} as const;
`

fs.writeFileSync(OUT_TS, file, "utf8")
console.log(`✅ Wrote ${OUT_TS}`)
